# Rebuilds src/calc.js from the calc/ folder of a nthGP/pokemmo-damage-calc build:
#   python scripts/bundle_calc.py path/to/calc src/calc.js
import os, json, sys
root, out = sys.argv[1], sys.argv[2]
mods = {}
for d, _, fs in os.walk(root):
    for f in fs:
        if f.endswith('.js'):
            p = os.path.relpath(os.path.join(d, f), root).replace(os.sep, '/')[:-3]
            mods[p] = open(os.path.join(d, f), encoding='utf-8').read()
parts = ["""// PokeMMO damage calc engine, bundled for the browser from nthGP/pokemmo-damage-calc (a fork of
// smogon/damage-calc, MIT licence: Copyright (c) 2013-2024 Honko, Austin and contributors).
// Generated by a script: don't edit by hand. Exposes window.Calc (calculate, Generations, Pokemon, Move, Field).
(function () {
var defs = {}, cache = {};
function resolve(from, req) {
    var parts = from.split('/'); parts.pop();
    req.split('/').forEach(function (s) { if (s === '..') parts.pop(); else if (s !== '.') parts.push(s); });
    var p = parts.join('/');
    return defs[p] ? p : p + '/index';
}
function load(p) {
    if (cache[p]) return cache[p].exports;
    var module = cache[p] = { exports: {} };
    defs[p].call(module.exports, function (r) { return load(resolve(p, r)); }, module, module.exports);
    return module.exports;
}
"""]
for p, src in sorted(mods.items()):
    parts.append("defs[%s] = function (require, module, exports) {\n%s\n};\n" % (json.dumps(p), src))
parts.append("window.Calc = load('index');\nwindow.Calc.getFinalSpeed = load('mechanics/util').getFinalSpeed;\n})();\n")
open(out, 'w', encoding='utf-8').write(''.join(parts))
print(len(mods), 'modules', os.path.getsize(out), 'bytes')
